
import streamlit as st
import pandas as pd
import joblib
import numpy as np


# ============================================================
# PAGE CONFIGURATION
# ============================================================

st.set_page_config(
    page_title="House Price Predictor",
    page_icon="🏠",
    layout="wide"
)


# ============================================================
# LOAD MODEL
# ============================================================

@st.cache_resource
def load_model():

    return joblib.load("House_price_model.pkl" )


model = load_model()


# ============================================================
# TITLE
# ============================================================

st.title("House Price Prediction")

st.write(
    "Enter the property details below to estimate "
    "the house price."
)

st.divider()

# ============================================================
# INPUT SECTION
# ============================================================

col1, col2 = st.columns(2)

with col1:

    area_type = st.selectbox(
        "Area Type",
        [
            "Super built-up Area",
            "Built-up Area",
            "Plot Area",
            "Carpet Area"
        ]
    )

    availability = st.text_input(
        "Availability",
        value="Ready To Move"
    )

    location = st.text_input(
        "Location",
        value="Whitefield"
    )

    society = st.text_input(
        "Society",
        value="Unknown"
    )

with col2:

    size = st.number_input(
        "BHK",
        min_value=1.0,
        max_value=20.0,
        value=2.0,
        step=1.0
    )

    total_sqft = st.number_input(
        "Total Square Feet",
        min_value=100.0,
        max_value=20000.0,
        value=1000.0,
        step=50.0
    )

    bath = st.number_input(
        "Bathrooms",
        min_value=1.0,
        max_value=20.0,
        value=2.0,
        step=1.0
    )

    balcony = st.number_input(
        "Balconies",
        min_value=0.0,
        max_value=10.0,
        value=1.0,
        step=1.0
    )

st.divider()


# ============================================================
# PREDICTION
# ============================================================

if st.button(
    "🔮 Predict House Price",
    use_container_width=True
):

    input_data = pd.DataFrame({
        "area_type": [area_type],
        "availability": [availability],
        "location": [location],
        "size": [size],
        "society": [society],
        "total_sqft": [total_sqft],
        "bath": [bath],
        "balcony": [balcony]
    })

    prediction = model.predict(
        input_data
    )[0]

    # ========================================================
    # DISPLAY RESULT
    # ========================================================

    st.success(
        "Prediction completed successfully!"
    )

    st.metric(
        label="Estimated House Price",
        value=f"₹ {prediction:.2f} Lakhs"
    )


    st.info(
        "This is an estimated price generated by "
        "a model and should not be "
        "treated as an exact market valuation."
    )
